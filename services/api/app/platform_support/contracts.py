"""Small OS capability contracts; no native imports or knowledge rules."""
from dataclasses import dataclass
from pathlib import Path
from typing import ContextManager, Protocol


class UnsupportedPlatform(ValueError):
    pass


class UnsafeFile(ValueError):
    pass


@dataclass(frozen=True)
class DirectoryLayout:
    data: Path
    cache: Path
    logs: Path
    configuration: Path


@dataclass(frozen=True)
class RuntimeLayout:
    root: Path
    python: Path
    backend: Path
    model: Path
    ocr_models: Path


class PrivateFiles(Protocol):
    def directory(self, path: Path) -> None: ...
    def safe_path(self, path: Path, *, create: bool = False) -> None: ...
    def read(self, path: Path, *, maximum: int, private: bool = True,
             parents: bool = False, permissions: int | None = None) -> bytes | None: ...
    def atomic_write(self, path: Path, value: bytes) -> None: ...
    def lock(self, path: Path, *, exclusive: bool) -> ContextManager: ...
    def protect(self, path: Path) -> None: ...
    def reserve(self, path: Path) -> None: ...
    def publish_file(self, stage: Path, destination: Path) -> None: ...
    def publish_directory(self, stage: Path, destination: Path) -> None: ...


class OwnedWorker(Protocol):
    @property
    def pid(self) -> int: ...
    def poll(self) -> int | None: ...
    def read_ready(self) -> bytes | None: ...
    def close_ready(self) -> None: ...
    def stop(self) -> None: ...


class OwnedProcesses(Protocol):
    def start_worker(self, arguments: list[str], environment: dict[str, str],
                     startup: bytes, diagnostics) -> OwnedWorker: ...
    def watch_parent(self, descriptor: int, on_eof) -> None: ...
    def install_stop_handlers(self, stop) -> None: ...
    def stop_current_worker(self) -> None: ...
    def notify_ready(self, descriptor: int) -> None: ...
    def exec(self, command: str, arguments: list[str], environment: dict[str, str]) -> None: ...


class ExternalCapabilities(Protocol):
    def resolve_cli(self, path: str = '') -> str: ...
    def run_cli(self, executable: str, arguments: list[str], timeout: float,
                directory: Path | None, maximum_directory_bytes: int | None): ...
    def recognize_image(self, path: Path) -> str: ...
